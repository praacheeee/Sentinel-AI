import React from "react";
import { Wrench, Clock, DollarSign, Package } from "lucide-react";

import SectionContainer from "@/components/common/SectionContainer";
import SectionHeader from "@/components/common/SectionHeader";
import InfoCard from "@/components/common/InfoCard";
import EmptyState from "@/components/common/EmptyState";
import LoadingSkeleton from "@/components/common/LoadingSkeleton";
import {
  SEVERITY_BADGE_STYLES,
  type IncidentSeverity,
} from "@/constants/incident";

export interface RepairStep {
  id: string;
  title: string;
  description: string;
  priority: IncidentSeverity;
}

export interface RepairRecommendationProps {
  overview: string;
  estimatedTime: string;
  estimatedCost: string;
  requiredResources: string[];
  steps: RepairStep[];
  loading?: boolean;
  className?: string;
}

export const RepairRecommendation: React.FC<RepairRecommendationProps> = ({
  overview,
  estimatedTime,
  estimatedCost,
  requiredResources,
  steps,
  loading = false,
  className = "",
}) => {
  const isEmpty = !overview.trim() && steps.length === 0;

  return (
    <SectionContainer className={className}>
      <SectionHeader
        title="Repair Recommendation"
        subtitle="AI-generated recovery strategy and implementation guidance."
        icon={Wrench}
      />

      {loading ? (
        <LoadingSkeleton variant="card" count={2} />
      ) : isEmpty ? (
        <EmptyState
          title="No repair recommendation"
          description="Run AI analysis to generate repair recommendations."
        />
      ) : (
        <div className="flex flex-col gap-6">
          {overview.trim() && (
            <InfoCard
              title="Recommendation Overview"
              description="Summary of the AI-generated recovery strategy."
            >
              <p className="text-base text-[#F0F6FC] leading-relaxed">
                {overview}
              </p>
            </InfoCard>
          )}

          {(estimatedTime || estimatedCost || requiredResources.length > 0) && (
            <InfoCard
              title="Planning Information"
              description="Estimated execution details."
            >
              <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
                {estimatedTime && (
                  <div className="p-4 rounded-xl bg-[#21262D] border border-[#30363D] flex items-center gap-3">
                    <div className="p-2 rounded-lg bg-[#161B22] border border-[#30363D] text-[#8B949E] shrink-0">
                      <Clock className="w-4 h-4 text-current" aria-hidden="true" />
                    </div>
                    <div>
                      <span className="text-xs text-[#8B949E] block">Estimated Time</span>
                      <span className="text-sm font-semibold text-[#F0F6FC]">{estimatedTime}</span>
                    </div>
                  </div>
                )}

                {estimatedCost && (
                  <div className="p-4 rounded-xl bg-[#21262D] border border-[#30363D] flex items-center gap-3">
                    <div className="p-2 rounded-lg bg-[#161B22] border border-[#30363D] text-[#8B949E] shrink-0">
                      <DollarSign className="w-4 h-4 text-current" aria-hidden="true" />
                    </div>
                    <div>
                      <span className="text-xs text-[#8B949E] block">Estimated Cost</span>
                      <span className="text-sm font-semibold text-[#F0F6FC]">{estimatedCost}</span>
                    </div>
                  </div>
                )}

                {requiredResources.length > 0 && (
                  <div className="p-4 rounded-xl bg-[#21262D] border border-[#30363D] flex flex-col gap-2">
                    <div className="flex items-center gap-2">
                      <Package className="w-4 h-4 text-[#8B949E]" aria-hidden="true" />
                      <span className="text-xs text-[#8B949E]">Required Resources</span>
                    </div>
                    <div className="flex flex-wrap gap-1.5">
                      {requiredResources.map((res, index) => (
                        <span
                          key={`${res}-${index}`}
                          className="px-2 py-0.5 rounded-md text-xs bg-[#161B22] text-[#F0F6FC] border border-[#30363D]"
                        >
                          {res}
                        </span>
                      ))}
                    </div>
                  </div>
                )}
              </div>
            </InfoCard>
          )}

          {steps.length > 0 && (
            <InfoCard
              title="Recommended Repair Steps"
              description="Ordered implementation plan generated by AI."
            >
              <div className="flex flex-col gap-3">
                {steps.map((step, idx) => (
                  <div
                    key={step.id}
                    className="p-4 rounded-xl bg-[#21262D] border border-[#30363D] flex flex-col gap-2"
                  >
                    <div className="flex items-center justify-between gap-3">
                      <div className="flex items-center gap-2.5">
                        <span className="flex items-center justify-center w-5 h-5 rounded-full bg-[#161B22] border border-[#30363D] text-xs font-semibold text-[#8B949E]">
                          {idx + 1}
                        </span>
                        <h4 className="text-sm font-semibold text-[#F0F6FC]">{step.title}</h4>
                      </div>
                      <span
                        className={`text-xs font-semibold px-2.5 py-1 rounded-full border ${
                          SEVERITY_BADGE_STYLES[step.priority]
                        }`}
                      >
                        {step.priority}
                      </span>
                    </div>
                    <p className="text-xs text-[#8B949E] leading-relaxed pl-7">
                      {step.description}
                    </p>
                  </div>
                ))}
              </div>
            </InfoCard>
          )}
        </div>
      )}
    </SectionContainer>
  );
};

export default React.memo(RepairRecommendation);