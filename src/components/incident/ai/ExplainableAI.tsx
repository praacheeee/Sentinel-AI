import React from "react";
import { BrainCircuit } from "lucide-react";

import SectionContainer from "@/components/common/SectionContainer";
import SectionHeader from "@/components/common/SectionHeader";
import InfoCard from "@/components/common/InfoCard";
import EmptyState from "@/components/common/EmptyState";
import LoadingSkeleton from "@/components/common/LoadingSkeleton";
import { formatConfidence, normalizePercentage } from "@/constants/incident";

export interface ExplanationFactor {
  id: string;
  title: string;
  description: string;
  importance: number;
}

export interface ExplainableAIProps {
  confidence: number;
  summary: string;
  factors: ExplanationFactor[];
  loading?: boolean;
  className?: string;
}

export const ExplainableAI: React.FC<ExplainableAIProps> = ({
  confidence,
  summary,
  factors,
  loading = false,
  className = "",
}) => {
  const isEmpty = !summary.trim() && factors.length === 0;

  return (
    <SectionContainer className={className}>
      <SectionHeader
        title="Explainable AI"
        subtitle="Understand why the AI reached this assessment."
        icon={BrainCircuit}
      />

      {loading ? (
        <LoadingSkeleton variant="card" count={2} />
      ) : isEmpty ? (
        <EmptyState
          title="No AI explanation available"
          description="Run an AI analysis to generate explainable insights."
        />
      ) : (
        <div className="flex flex-col gap-6">
          {summary.trim() && (
            <InfoCard
              title="AI Summary"
              description="High-level explanation generated by the AI."
            >
              <div className="flex flex-col gap-4">
                <p className="text-base text-[#F0F6FC] leading-relaxed">
                  {summary}
                </p>

                <div className="flex items-center gap-2 pt-2 border-t border-[#30363D]">
                  <span className="text-xs font-medium text-[#8B949E]">
                    Overall AI Confidence:
                  </span>
                  <span className="text-sm font-semibold text-[#58A6FF] bg-[#58A6FF]/10 px-2.5 py-0.5 rounded-full border border-[#58A6FF]/30">
                    {formatConfidence(confidence)}
                  </span>
                </div>
              </div>
            </InfoCard>
          )}

          {factors.length > 0 && (
            <InfoCard
              title="Key Decision Factors"
              description="Primary factors influencing the AI assessment."
            >
              <section
                aria-label="Key Decision Factors List"
                className="flex flex-col gap-3"
              >
                {factors.map((factor) => {
                  const importancePercentage = Math.round(
                    normalizePercentage(factor.importance)
                  );

                  return (
                    <article
                      key={factor.id}
                      className="p-4 rounded-xl bg-[#21262D] border border-[#30363D] flex flex-col gap-3"
                    >
                      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-1 sm:gap-4">
                        <h4 className="text-sm font-semibold text-[#F0F6FC]">
                          {factor.title}
                        </h4>
                        <span className="text-xs font-semibold text-[#58A6FF] shrink-0">
                          {importancePercentage}% Importance
                        </span>
                      </div>

                      <p className="text-xs text-[#8B949E] leading-relaxed">
                        {factor.description}
                      </p>

                      <div className="w-full bg-[#161B22] border border-[#30363D] rounded-full h-2 overflow-hidden">
                        <div
                          className="bg-[#58A6FF] h-full rounded-full transition-all"
                          style={{ width: `${importancePercentage}%` }}
                          role="progressbar"
                          aria-label={`Importance of ${factor.title}`}
                          aria-valuenow={importancePercentage}
                          aria-valuemin={0}
                          aria-valuemax={100}
                        />
                      </div>
                    </article>
                  );
                })}
              </section>
            </InfoCard>
          )}
        </div>
      )}
    </SectionContainer>
  );
};

export default React.memo(ExplainableAI);